class UnixSocket {
  public:
    UnixSocket() : fd_(socket(AF_UNIX, SOCK_STREAM, 0)) {
        if (fd_ == -1) {
            throw std::system_error(errno, std::system_category(),
                                    "Socket creation failed");
        }
    }

    ~UnixSocket() {
        if (fd_ != -1) {
            close(fd_);
        }
    }

    // Delete copy operations
    UnixSocket(const UnixSocket &) = delete;
    UnixSocket &operator=(const UnixSocket &) = delete;

    // Move operations
    UnixSocket(UnixSocket &&other) noexcept : fd_(other.fd_) { other.fd_ = -1; }

    UnixSocket &operator=(UnixSocket &&other) noexcept {
        if (this != &other) {
            if (fd_ != -1) {
                close(fd_);
            }
            fd_ = other.fd_;
            other.fd_ = -1;
        }
        return *this;
    }

    [[nodiscard]] int get() const { return fd_; }

  private:
    int fd_;
};

class AtchimClient {
  public:
    explicit AtchimClient(std::string_view socketPath)
        : socketPath_(socketPath) {
        if (socketPath_.empty() ||
            socketPath_.length() > sizeof(sockaddr_un::sun_path) - 1) {
            throw std::invalid_argument("Invalid socket path");
        }
    }

    void sendCommand(std::string_view command) const {
        if (command.empty()) {
            throw std::invalid_argument("Empty command");
        }

        UnixSocket sock;
        connectToServer(sock);
        sendAll(sock.get(), command);
        sendAll(sock.get(), "\n");
    }

  private:
    void connectToServer(const UnixSocket &sock) const {
        sockaddr_un address{};
        address.sun_family = AF_UNIX;

        // Safer copy and null-termination
        std::strncpy(address.sun_path, socketPath_.data(),
                     sizeof(address.sun_path) - 1);
        address.sun_path[sizeof(address.sun_path) - 1] = '\0';

        socklen_t addrLen =
            offsetof(sockaddr_un, sun_path) + std::strlen(address.sun_path) + 1;

        if (connect(sock.get(), reinterpret_cast<sockaddr *>(&address),
                    addrLen) == -1) {
            throw std::system_error(errno, std::system_category(),
                                    "Connection to server failed");
        }
    }

    static void sendAll(int fd, std::string_view data) {
        const char *buffer = data.data();
        size_t remaining = data.length();

        while (remaining > 0) {
            ssize_t written = write(fd, buffer, remaining);
            if (written == -1) {
                if (errno == EINTR) {
                    continue;
                }
                throw std::system_error(errno, std::system_category(),
                                        "Failed to send data");
            }
            remaining -= written;
            buffer += written;
        }
    }

    std::string socketPath_;
};

int parseLimit(int argc, char *argv[], int &index) {
    int limit = 50;
    if (index + 1 < argc && std::string_view(argv[index]) == "-n") {
        limit = std::stoi(argv[index + 1]);
        index += 2;
    }
    if (limit < 1)
        limit = 1;
    if (static_cast<size_t>(limit) > MAX_HISTORY_LIMIT) {
        limit = static_cast<int>(MAX_HISTORY_LIMIT);
    }
    return limit;
}

int printHistory(int argc, char *argv[], int start, bool requireQuery) {
    int index = start;
    const bool printEpoch =
        index < argc && std::string_view(argv[index]) == "--epoch";
    if (printEpoch) {
        ++index;
    }
    const int limit = parseLimit(argc, argv, index);
    const std::string query = joinArgs(argc, argv, index);

    if (requireQuery && query.empty()) {
        std::cerr << "search requires a query\n";
        return EXIT_FAILURE;
    }

    atchim::SQLiteDatabase db(defaultDatabasePath());
    const bool filtered = !query.empty();
    const std::string timeColumn = printEpoch ? "strftime('%s', TIME)" : "TIME";
    const std::string sql = filtered
                                ? "SELECT ID, " + timeColumn +
                                      ", HOST, COMMAND FROM HISTORY "
                                      "WHERE COMMAND LIKE ?1 OR HOST LIKE ?1 "
                                      "ORDER BY ID DESC LIMIT ?2;"
                                : "SELECT ID, " + timeColumn +
                                      ", HOST, COMMAND FROM HISTORY "
                                      "ORDER BY ID DESC LIMIT ?1;";
    atchim::Statement stmt(db.get(), sql);
    if (filtered) {
        stmt.bindText(1, "%" + query + "%");
        stmt.bindInt(2, limit);
    } else {
        stmt.bindInt(1, limit);
    }

    while (true) {
        const int rc = stmt.step();
        if (rc == SQLITE_DONE)
            break;
        if (rc != SQLITE_ROW) {
            throw std::runtime_error(sqlite3_errmsg(db.get()));
        }

        const auto *time =
            reinterpret_cast<const char *>(sqlite3_column_text(stmt.get(), 1));
        const auto *host =
            reinterpret_cast<const char *>(sqlite3_column_text(stmt.get(), 2));
        const auto *command =
            reinterpret_cast<const char *>(sqlite3_column_text(stmt.get(), 3));

        std::cout << sqlite3_column_int64(stmt.get(), 0) << '\t'
                  << (time ? time : "") << '\t' << (host ? host : "") << '\t'
                  << (command ? command : "") << '\n';
    }

    return EXIT_SUCCESS;
}

int printSuggestion(int argc, char *argv[], int start) {
    const std::string prefix = joinArgs(argc, argv, start);
    if (prefix.empty()) {
        return EXIT_SUCCESS;
    }

    atchim::SQLiteDatabase db(defaultDatabasePath());
    atchim::Statement exactPrefix(
        db.get(), "SELECT COMMAND FROM HISTORY "
                  "WHERE substr(COMMAND, 1, length(?1)) = ?1 AND COMMAND <> ?1 "
                  "ORDER BY ID DESC LIMIT 1;");
    exactPrefix.bindText(1, prefix);

    int rc = exactPrefix.step();
    if (rc == SQLITE_ROW) {
        std::cout << exactPrefix.columnText(0) << '\n';
        return EXIT_SUCCESS;
    }
    if (rc != SQLITE_DONE) {
        throw std::runtime_error(sqlite3_errmsg(db.get()));
    }

    return EXIT_SUCCESS;
}

void insertHistoryEntry(std::string_view command, std::string_view host) {
    atchim::SQLiteDatabase db(defaultDatabasePath(),
                              SQLITE_OPEN_READWRITE | SQLITE_OPEN_CREATE);
    atchim::createAtchimSchema(db);

    atchim::Statement insert(
        db.get(), "INSERT INTO HISTORY(COMMAND, HOST) VALUES (?1, ?2);");
    insert.bindText(1, command);
    insert.bindText(2, host.empty() ? "local" : host);
    if (insert.step() != SQLITE_DONE) {
        throw std::runtime_error(sqlite3_errmsg(db.get()));
    }
}

int importAtuin(int argc, char *argv[]) {
    if (argc > 4) {
        std::cerr << "Usage: atchim import atuin [history.db]\n";
        return EXIT_FAILURE;
    }

    const std::filesystem::path sourcePath =
        argc == 4 ? std::filesystem::path(argv[3]) : defaultAtuinDatabasePath();
    if (!std::filesystem::exists(sourcePath)) {
        throw std::runtime_error("Atuin history database not found: " +
                                 sourcePath.string());
    }

    atchim::SQLiteDatabase source(sourcePath, SQLITE_OPEN_READONLY);
    atchim::SQLiteDatabase dest(defaultDatabasePath(),
                                SQLITE_OPEN_READWRITE | SQLITE_OPEN_CREATE);
    atchim::createAtchimSchema(dest);

    const bool hasDeletedAt =
        atchim::tableHasColumn(source, "history", "deleted_at");
    const std::string selectSql =
        hasDeletedAt
            ? "SELECT command, "
              "COALESCE(NULLIF(hostname, ''), 'local'), "
              "datetime(timestamp / 1000000000, 'unixepoch') "
              "FROM history WHERE deleted_at IS NULL ORDER BY timestamp ASC;"
            : "SELECT command, "
              "COALESCE(NULLIF(hostname, ''), 'local'), "
              "datetime(timestamp / 1000000000, 'unixepoch') "
              "FROM history ORDER BY timestamp ASC;";

    atchim::Statement select(source.get(), selectSql);
    atchim::Statement insert(dest.get(),
                             "INSERT INTO HISTORY(COMMAND, HOST, TIME) "
                             "SELECT ?1, ?2, ?3 "
                             "WHERE NOT EXISTS ("
                             "  SELECT 1 FROM HISTORY "
                             "  WHERE COMMAND = ?1 AND HOST = ?2 AND TIME = ?3"
                             ");");

    size_t imported = 0;
    size_t skipped = 0;
    dest.execute("BEGIN IMMEDIATE;");
    try {
        while (true) {
            const int rc = select.step();
            if (rc == SQLITE_DONE)
                break;
            if (rc != SQLITE_ROW) {
                throw std::runtime_error(sqlite3_errmsg(source.get()));
            }

            const std::string command(select.columnText(0));
            const std::string host(select.columnText(1));
            const std::string time(select.columnText(2));
            if (command.empty() || time.empty()) {
                ++skipped;
                continue;
            }

            insert.bindText(1, command);
            insert.bindText(2, host.empty() ? "local" : host);
            insert.bindText(3, time);

            if (insert.step() != SQLITE_DONE) {
                throw std::runtime_error(sqlite3_errmsg(dest.get()));
            }
            if (sqlite3_changes(dest.get()) > 0) {
                ++imported;
            } else {
                ++skipped;
            }
            insert.reset();
        }
        dest.execute("COMMIT;");
    } catch (...) {
        dest.execute("ROLLBACK;");
        throw;
    }

    std::cout << "Imported " << imported << " Atuin commands into "
              << defaultDatabasePath() << " (" << skipped << " skipped).\n";
    return EXIT_SUCCESS;
}

int logCommand(int argc, char *argv[], int start) {
    std::optional<std::string> host;
    if (start + 1 < argc && std::string_view(argv[start]) == "--host") {
        host = argv[start + 1];
        start += 2;
    }
    if (start < argc && std::string_view(argv[start]) == "--") {
        ++start;
    }

    const std::string command = joinArgs(argc, argv, start);
    if (command.empty()) {
        printUsage();
        return EXIT_FAILURE;
    }

    const std::string resolvedHost = host.value_or("local");
    const std::string message = host ? resolvedHost + "\t" + command : command;

    if (!envFlagEnabled("ATCHIM_DAEMON")) {
        insertHistoryEntry(command, resolvedHost);
        return EXIT_SUCCESS;
    }

    try {
        const AtchimClient client(
            getEnvOrDefault("ATCHIM_SOCKET", DEFAULT_SOCKET_PATH));
        client.sendCommand(message);
    } catch (const std::system_error &) {
        insertHistoryEntry(command, resolvedHost);
    }

    return EXIT_SUCCESS;
}

int main(int argc, char *argv[]) try {
    // Prevent SIGPIPE from terminating the process
    std::signal(SIGPIPE, SIG_IGN);

    if (argc < 2) {
        printUsage();
        return EXIT_FAILURE;
    }

    const std::string_view action(argv[1]);
    if (action == "init") {
        if (argc == 3 && std::string_view(argv[2]) == "zsh") {
            printZshInit();
            return EXIT_SUCCESS;
        }
        std::cerr << "Usage: atchim init zsh\n";
        return EXIT_FAILURE;
    }
    if (action == "import") {
        if (argc >= 3 && std::string_view(argv[2]) == "atuin") {
            return importAtuin(argc, argv);
        }
        std::cerr << "Usage: atchim import atuin [history.db]\n";
        return EXIT_FAILURE;
    }
    if (action == "start" || action == "log") {
        return logCommand(argc, argv, 2);
    }
    if (action == "history") {
        return printHistory(argc, argv, 2, false);
    }
    if (action == "search") {
        return printHistory(argc, argv, 2, true);
    }
    if (action == "suggest") {
        return printSuggestion(argc, argv, 2);
    }
    if (action == "delete") {
        if (argc < 3) {
            std::cerr << "Usage: atchim delete <id>\n";
            return EXIT_FAILURE;
        }
        const int id = std::stoi(argv[2]);
        atchim::SQLiteDatabase db(defaultDatabasePath(),
                                  SQLITE_OPEN_READWRITE | SQLITE_OPEN_CREATE);
        atchim::createAtchimSchema(db);
        atchim::Statement stmt(db.get(), "DELETE FROM HISTORY WHERE ID = ?1;");
        stmt.bindInt(1, id);
        if (stmt.step() != SQLITE_DONE) {
            throw std::runtime_error(sqlite3_errmsg(db.get()));
        }
        if (sqlite3_changes(db.get()) == 0) {
            std::cerr << "No history entry found with ID " << id << "\n";
            return EXIT_FAILURE;
        }
        std::cout << "Deleted history entry " << id << "\n";
        return EXIT_SUCCESS;
    }
    if (action == "clear") {
        atchim::SQLiteDatabase db(defaultDatabasePath(),
                                  SQLITE_OPEN_READWRITE | SQLITE_OPEN_CREATE);
        atchim::createAtchimSchema(db);
        atchim::Statement stmt(db.get(), "DELETE FROM HISTORY;");
        if (stmt.step() != SQLITE_DONE) {
            throw std::runtime_error(sqlite3_errmsg(db.get()));
        }
        const int changed = sqlite3_changes(db.get());
        std::cout << "Cleared " << changed << " history entries\n";
        return EXIT_SUCCESS;
    }
    if (action == "--help" || action == "-h") {
        printUsage();
        return EXIT_SUCCESS;
    }

    return logCommand(argc, argv, 1);

} catch (const std::exception &e) {
    std::cerr << "Error: " << e.what() << "\n";
    return EXIT_FAILURE;
}
