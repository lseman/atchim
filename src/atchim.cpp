int pickTheme(char *program) {
    std::vector<std::filesystem::path> files;
    for (const auto &entry : std::filesystem::directory_iterator(themeDirectory()))
        if (entry.is_regular_file() && entry.path().extension() == ".theme") files.push_back(entry.path());
    std::sort(files.begin(), files.end());
    auto selected = atchim::pickTheme(files);
    if (!selected) return EXIT_SUCCESS;
    char themesArg[] = "themes", setArg[] = "set";
    char *args[] = {program, themesArg, setArg, selected->data()};
    return themes(4, args);
}

int themes(int argc, char *argv[]) {
    if ((argc == 2 && isatty(STDIN_FILENO) && isatty(STDOUT_FILENO)) ||
        (argc == 3 && std::string_view(argv[2]) == "pick")) return pickTheme(argv[0]);
    const std::string action = argc > 2 ? argv[2] : "list";
    const bool preview = action == "preview" || action == "preview-live";
    const bool set = action == "set";
    if (argc > 4 || ((set || preview) && argc != 4) ||
        (action == "list" && argc != 2 && argc != 3))
        throw std::invalid_argument("Usage: atchim themes [list | preview NAME | set NAME]");
    const std::string requested = (set || preview) ? argv[3] : (action == "list" || action == "names") ? "" : action;
    std::vector<std::filesystem::path> files;
    for (const auto &entry : std::filesystem::directory_iterator(themeDirectory()))
        if (entry.is_regular_file() && entry.path().extension() == ".theme" &&
            (requested.empty() || entry.path().stem() == requested)) files.push_back(entry.path());
    std::sort(files.begin(), files.end());
    if (files.empty()) throw std::invalid_argument("No matching theme: " + requested);
    if (action == "names") {
        for (const auto &file : files) std::cout << file.stem().string() << '\n';
        return EXIT_SUCCESS;
    }
    if (set) {
        const auto preference = themePreference();
        std::filesystem::create_directories(preference.parent_path());
        std::ofstream out(preference);
        out << requested << '\n';
        out.close();
        if (!out) throw std::runtime_error("Cannot save theme preference");
        std::cout << "Theme saved: " << requested << ". Open Ctrl-R to see it.\n"
                  << "An exported ATCHIM_THEME takes precedence.\n";
        return EXIT_SUCCESS;
    }
    const bool color = (isatty(STDOUT_FILENO) || action == "preview-live") && !std::getenv("NO_COLOR");
    for (const auto &file : files) {
        std::map<std::string, std::string> palette;
        std::ifstream input(file);
        std::string line;
        while (std::getline(input, line)) {
            const auto equals = line.find('=');
            if (equals == std::string::npos) continue;
            auto value = line.substr(equals + 1);
            if (value.size() == 9 && value.front() == '"' && value.back() == '"') value = value.substr(1, 7);
            if (value.size() == 7 && value[0] == '#' && std::all_of(value.begin()+1, value.end(), [](unsigned char c) { return std::isxdigit(c); }))
                palette[line.substr(0, equals)] = value;
        }
        const auto paint = [&](const std::string &role, const std::string &text) {
            const auto found = palette.find("ATCHIM_COLOR_" + role);
            if (!color || found == palette.end()) return text;
            const auto &hex = found->second;
            return std::string("\033[38;2;") + std::to_string(std::stoi(hex.substr(1,2), nullptr,16)) + ";" +
                std::to_string(std::stoi(hex.substr(3,2), nullptr,16)) + ";" + std::to_string(std::stoi(hex.substr(5,2), nullptr,16)) + "m" + text + "\033[0m";
        };
        std::cout << "\n  " << paint("COMMAND", file.stem().string()) << "\n  ";
        for (const auto *role : {"COMMAND", "STRING", "OPTION", "OPERATOR", "PATH", "MUTED"})
            std::cout << paint(role, "██ ");
        std::cout << "\n  " << paint("MUTED", "2min ago  ") << paint("COMMAND", "git ")
                  << paint("FG", "commit ") << paint("OPTION", "-m ") << paint("STRING", "\"ship it\" ")
                  << paint("OPERATOR", "&& ") << paint("COMMAND", "ls ") << paint("PATH", "./src") << "\n";
    }
    if (action == "preview-live") {
        std::cout << "\n  Navigate to compare colors. Enter saves this theme.\n";
    } else std::cout << "\n  Apply: atchim themes set NAME\n\n";
    return EXIT_SUCCESS;
}

std::filesystem::path selectedTheme() {
    std::string name = getEnvOrDefault("ATCHIM_THEME", "");
    if (name.empty()) {
        std::ifstream preference(themePreference());
        std::getline(preference, name);
        if (name.find('/') != std::string::npos) name.clear();
    }
    if (name.empty()) name = "midnight";
    if (name.find('/') != std::string::npos) return name;
    const auto directory = themeDirectory();
    if (std::filesystem::is_regular_file(directory / name)) return directory / name;
    return directory / (name + ".theme");
}

int pickHistory(int argc, char *argv[]) {
    bool directory = false, shell = false;
    bool details = getEnvOrDefault("ATCHIM_PREVIEW", "0") != "0";
    int index = 2;
    for (; index < argc; ++index) {
        const std::string_view option(argv[index]);
        if (option == "--") { ++index; break; }
        if (option == "--cwd") directory = true;
        else if (option == "--shell") shell = true;
        else if (option == "--details") details = true;
        else if (option.starts_with("-")) throw std::invalid_argument("Unknown picker option: " + std::string(option));
        else break;
    }
    auto selection = atchim::pickHistory(defaultDatabasePath(), selectedTheme(), joinArgs(argc, argv, index), directory, details);
    if (!selection) return 130;
    if (shell) std::cout << (selection->execute ? "execute:" : "insert:");
    std::cout << selection->command;
    return EXIT_SUCCESS;
}

int main(int argc, char *argv[]) try {
    std::ios::sync_with_stdio(false);
    std::cin.tie(nullptr);
    // Prevent SIGPIPE from terminating the process
    std::signal(SIGPIPE, SIG_IGN);

    if (argc < 2) {
        printUsage();
        return EXIT_FAILURE;
    }

    const std::string_view action(argv[1]);
    if (action == "pick") return pickHistory(argc, argv);
    if (action == "themes") return themes(argc, argv);
    if (action == "init") {
        if (argc == 3 && std::string_view(argv[2]) == "zsh") {
            printZshInit();
            return EXIT_SUCCESS;
        }
        std::cerr << "Usage: atchim init zsh\n";
        return EXIT_FAILURE;
    }
    if (action == "import" || action == "migrate") {
        if (argc >= 3 && std::string_view(argv[2]) == "atuin") {
            return importAtuin(argc, argv);
        }
        std::cerr << "Usage: atchim import atuin [history.db]\n";
        return EXIT_FAILURE;
    }
    if (action == "start" || action == "log") {
        return logCommand(argc, argv, 2);
    }
    if (action == "history") {
        return printHistory(argc, argv, 2, false);
    }
    if (action == "search") {
        return printHistory(argc, argv, 2, true);
    }
    if (action == "show" && argc == 3) return showEntry(argv[2]);
    if (action == "suggest") {
        return printSuggestion(argc, argv, 2);
    }
    if (action == "delete") {
        if (argc < 3) {
            std::cerr << "Usage: atchim delete <id>\n";
            return EXIT_FAILURE;
        }
        const int id = std::stoi(argv[2]);
        atchim::SQLiteDatabase db(defaultDatabasePath(),
                                  SQLITE_OPEN_READWRITE | SQLITE_OPEN_CREATE);
        atchim::createAtchimSchema(db);
        atchim::Statement stmt(db.get(), "DELETE FROM HISTORY WHERE ID = ?1;");
        stmt.bindInt(1, id);
        if (stmt.step() != SQLITE_DONE) {
            throw std::runtime_error(sqlite3_errmsg(db.get()));
        }
        if (sqlite3_changes(db.get()) == 0) {
            std::cerr << "No history entry found with ID " << id << "\n";
            return EXIT_FAILURE;
        }
        std::cout << "Deleted history entry " << id << "\n";
        return EXIT_SUCCESS;
    }
    if (action == "clear") {
        atchim::SQLiteDatabase db(defaultDatabasePath(),
                                  SQLITE_OPEN_READWRITE | SQLITE_OPEN_CREATE);
        atchim::createAtchimSchema(db);
        atchim::Statement stmt(db.get(), "DELETE FROM HISTORY;");
        if (stmt.step() != SQLITE_DONE) {
            throw std::runtime_error(sqlite3_errmsg(db.get()));
        }
        const int changed = sqlite3_changes(db.get());
        std::cout << "Cleared " << changed << " history entries\n";
        return EXIT_SUCCESS;
    }
    if (action == "--help" || action == "-h") {
        printUsage();
        return EXIT_SUCCESS;
    }

    return logCommand(argc, argv, 1);

} catch (const std::exception &e) {
    std::cerr << "Error: " << e.what() << "\n";
    return EXIT_FAILURE;
}
