bool envFlagEnabled(const char *name) {
    const char *value = std::getenv(name);
    if (!value)
        return false;

    const std::string_view flag(value);
    return flag == "1" || flag == "true" || flag == "TRUE" || flag == "yes" ||
           flag == "YES" || flag == "on" || flag == "ON";
}

std::filesystem::path defaultDatabasePath() {
    if (const char *db = std::getenv("ATCHIM_DB")) {
        return db;
    }
    const char *home = std::getenv("HOME");
    if (!home) {
        throw std::runtime_error(
            "HOME is not set; use ATCHIM_DB to pick a database");
    }
    return std::filesystem::path(home) / ".atchim.db";
}

std::filesystem::path defaultAtuinDatabasePath() {
    if (const char *db = std::getenv("ATUIN_DB")) {
        return db;
    }

    const char *home = std::getenv("HOME");
    if (!home) {
        throw std::runtime_error(
            "HOME is not set; pass a path to `atchim import atuin`");
    }

    if (const char *xdgDataHome = std::getenv("XDG_DATA_HOME")) {
        return std::filesystem::path(xdgDataHome) / "atuin" / "history.db";
    }

    return std::filesystem::path(home) / ".local" / "share" / "atuin" /
           "history.db";
}

std::string joinArgs(int argc, char *argv[], int start) {
    std::string out;
    for (int i = start; i < argc; ++i) {
        if (!out.empty())
            out += ' ';
        out += argv[i];
    }
    return out;
}

